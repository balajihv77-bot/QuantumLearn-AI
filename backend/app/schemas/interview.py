"""
QuantumLearn AI - Interview Pydantic Schemas
Defines request and response schemas for the AI Mock Interview system,
supporting live AI integration, rubric breakdowns, practice estimate labeling,
and provider status reporting.
"""

from typing import List, Optional, Dict, Any
from datetime import datetime
from pydantic import BaseModel, Field


class InterviewQuestionSchema(BaseModel):
    id: str
    question: str
    category: str
    difficulty: str
    hint: Optional[str] = None
    is_coding_question: bool = False
    coding_language: Optional[str] = None
    starter_code: Optional[str] = None
    follow_up_hint: Optional[str] = None
    effective_answer_guide: Optional[str] = None
    evaluation_criteria: List[str] = Field(default_factory=list)


class InterviewStartRequest(BaseModel):
    role: str = Field(..., description="Target job role, e.g. Python Developer, Full-Stack Developer")
    experience_level: str = Field(..., description="Target experience level: Fresher, Beginner, Intermediate, Experienced")
    interview_type: str = Field(..., description="Interview focus: Technical, HR, Coding, Mixed")
    difficulty: str = Field(..., description="Difficulty rating: Easy, Medium, Hard")
    question_count: int = Field(default=5, ge=1, le=20, description="Total question count for session")


class InterviewSessionResponse(BaseModel):
    session_id: str
    role: str
    experience_level: str
    interview_type: str
    difficulty: str
    question_count: int
    status: str  # in_progress, completed, cancelled
    current_question_index: int
    current_question: Optional[InterviewQuestionSchema] = None
    total_questions: int
    answered_count: int
    created_at: datetime
    completed_at: Optional[datetime] = None
    user_id: Optional[int] = None
    provider_mode: str = Field(default="demo", description="'live_ai' or 'demo'")
    is_live_ai: bool = Field(default=False, description="True if driven by live Google Gemini AI provider")


class InterviewAnswerRequest(BaseModel):
    question_id: str = Field(..., description="Identifier of the question being answered")
    answer_text: str = Field(..., description="Candidate's verbal/textual response")
    code_answer: Optional[str] = Field(None, description="Optional code snippet or implementation")


class InterviewAnswerResponse(BaseModel):
    session_id: str
    question_id: str
    status: str
    current_question_index: int
    total_questions: int
    is_completed: bool
    next_question: Optional[InterviewQuestionSchema] = None
    message: str
    score: Optional[int] = Field(None, description="Practice estimate score for submitted answer (0-100)")
    feedback: Optional[str] = Field(None, description="AI critique and assessment")
    suggested_follow_up: Optional[str] = Field(None, description="Relevant follow-up question")
    effective_answer_guide: Optional[str] = Field(None, description="Guidance on what an effective answer should include")
    rubric_breakdown: Optional[Dict[str, Any]] = Field(None, description="Rubric criteria breakdown")
    practice_estimate_notice: str = Field(
        default="Scores and feedback are practice estimates for preparation only.",
        description="Disclaimer indicating practice estimation"
    )
    provider_mode: str = Field(default="demo", description="'live_ai' or 'demo'")


class QuestionBreakdownSchema(BaseModel):
    question_id: str
    question_text: str
    category: str
    difficulty: str
    user_answer: str
    code_answer: Optional[str] = None
    score: int
    model_answer: str
    key_points: List[str] = Field(default_factory=list)
    feedback: Optional[str] = None
    suggested_follow_up: Optional[str] = None
    effective_answer_guide: Optional[str] = None
    rubric_breakdown: Optional[Dict[str, Any]] = None


class InterviewReportSchema(BaseModel):
    session_id: str
    role: str
    experience_level: str
    interview_type: str
    difficulty: str
    overall_score: int
    technical_correctness: int
    answer_relevance: int
    clarity: int
    problem_solving: int
    strengths: List[str]
    areas_for_improvement: List[str]
    question_breakdowns: List[QuestionBreakdownSchema]
    summary: str
    total_duration_seconds: int
    evaluation_mode: str = "in_memory_calibrated_rubric"
    provider_mode: str = "demo"
    is_live_ai: bool = False
    evaluation_rubric_used: str = "Technical Standard Rubric"
    rubric_weights: Dict[str, int] = Field(default_factory=dict)
    practice_estimate_notice: str = (
        "Scores and ratings are practice estimates generated by QuantumLearn AI Mock Interview "
        "and do not constitute an official employment evaluation."
    )


class InterviewFinishResponse(BaseModel):
    session_id: str
    status: str
    total_questions: int
    answered_questions: int
    duration_seconds: int
    report: Optional[InterviewReportSchema] = None
    provider_mode: str = "demo"


class InterviewSessionSummarySchema(BaseModel):
    session_id: str
    role: str
    experience_level: str
    interview_type: str
    difficulty: str
    status: str
    overall_score: Optional[int] = None
    total_questions: int
    answered_questions: int
    created_at: datetime
    completed_at: Optional[datetime] = None
    provider_mode: str = "demo"


class InterviewHistoryResponse(BaseModel):
    total: int
    interviews: List[InterviewSessionSummarySchema]


class InterviewHealthResponse(BaseModel):
    status: str
    service: str
    version: str
    active_sessions_count: int
    storage_mode: str
    provider_mode: str = "demo"
    is_live_ai_available: bool = False


class InterviewProviderStatusResponse(BaseModel):
    provider_configured: bool
    provider_name: str
    model_name: str
    active_mode: str  # "live_ai" or "demo"
    rubrics_supported: List[str]
    safety_guardrails_active: bool
    status_message: str
